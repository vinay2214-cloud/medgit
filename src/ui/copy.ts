export const roleLabel = (r: Role): string => copy.role[r];

export function copyForError(code: string, detail?: string): string {
  if (code === 'INVALID_SOURCE') return copy.err.INVALID_SOURCE(detail ?? 'A source');
  const v = (copy.err as Record<string, unknown>)[code];
  return typeof v === 'string' ? v : copy.err.generic;
}
